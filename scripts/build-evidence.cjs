const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'research', name), 'utf8'));
const data = {curriculum:read('curriculum.json'),sources:read('sources.json'),exams:[read('exams-math-a.json'),read('exams-math-advanced.json')]};
const moduleIds=new Set(['app.js','exam-modules.js','extension-modules.js'].flatMap(file=>[...fs.readFileSync(path.join(root,file),'utf8').matchAll(/\bid:\s*["']([^"']+)["']/g)].map(m=>m[1])));
for (const exam of data.exams) {
  if (exam.documents.length !== 5) throw new Error('Each exam must have five documents');
  for (const doc of exam.documents) {
    if (doc.questions.length !== doc.questionCount || new Set(doc.questions.map(q=>q.number)).size !== doc.questionCount) throw new Error(`Invalid counts: ${doc.filename}`);
    // Upload identifiers are analysis metadata, not public website links.
    delete doc.uploadPointer;
    for(const q of doc.questions) {
      q.extensionModuleIds=q.proposedModuleIds||[];
      delete q.proposedModuleIds;
      for(const id of [...q.moduleIds,...q.extensionModuleIds]) if(!moduleIds.has(id)) throw new Error(`Unimplemented module ${id}`);
    }
  }
}
fs.writeFileSync(path.join(root,'evidence.js'), '/* Generated by npm run evidence; edit research/*.json instead. */\nwindow.MathLabEvidence = '+JSON.stringify(data,null,2).replace(/</g,'\\u003c')+';\n');
console.log(`Evidence built: ${data.exams.reduce((n,e)=>n+e.documents.reduce((n,d)=>n+d.questions.length,0),0)} numbered questions`);
